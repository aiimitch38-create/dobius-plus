import { basename, join } from 'node:path'

export const TERMINAL_STATES = Object.freeze([
  'queued', 'running', 'waiting_external', 'ready_for_review', 'done', 'failed', 'abandoned'
])

export const LAYA_LABELS = Object.freeze([
  'fine', 'working', 'waiting-permission', 'stuck', 'failed', 'needs-human'
])

export function stateIsValid(state) {
  return TERMINAL_STATES.includes(state)
}

export function checkpointFor({ terminalId, provider = 'unknown', worktree = null, lastCommand = null,
  state = 'queued', ownedPids = [], artifactPath = null, nextAction = null, updatedAt = new Date().toISOString() }) {
  if (!terminalId || typeof terminalId !== 'string') throw new Error('terminalId is required')
  if (!stateIsValid(state)) throw new Error(`invalid terminal state: ${state}`)
  return { version: 1, provider, terminalId, worktree, lastCommand, state,
    ownedPids: [...new Set(ownedPids.filter((pid) => Number.isInteger(pid) && pid > 0))],
    artifactPath, nextAction, updatedAt }
}

export function reconcileCheckpoint(checkpoint, isPidAlive) {
  if (!checkpoint || !stateIsValid(checkpoint.state)) return null
  if (checkpoint.state !== 'running') return { ...checkpoint, reconciled: false }
  const pids = Array.isArray(checkpoint.ownedPids) ? checkpoint.ownedPids : []
  const alive = pids.some((pid) => Number.isInteger(pid) && isPidAlive(pid))
  if (alive || pids.length === 0) return { ...checkpoint, reconciled: false }
  return { ...checkpoint, state: 'failed', nextAction: checkpoint.nextAction || 'Inspect the interrupted terminal and resume safely',
    reconciled: true, interruption: 'interrupted: owned process exited before checkpoint recovery', updatedAt: new Date().toISOString() }
}

export function laneManifest({ laneId, worktree, basePort = 4300, stateRoot }) {
  if (!laneId || !/^[a-z0-9][a-z0-9._-]*$/i.test(laneId)) throw new Error('laneId must be filesystem-safe')
  if (!worktree) throw new Error('worktree is required')
  const root = stateRoot || join(worktree, '.dobius')
  return { version: 1, laneId, worktree, envrc: join(root, '.envrc'), logPath: join(root, 'logs'),
    runtimeDataPath: join(root, 'runtime'), checkpointPath: join(root, 'terminal-state.json'),
    env: { LANE_ID: laneId, PORT_BASE: String(basePort), DOBIUS_LANE_LOG_PATH: join(root, 'logs'),
      DOBIUS_LANE_RUNTIME_PATH: join(root, 'runtime') } }
}

export function envrcFor(manifest) {
  return `# Generated by Dobius; provider-neutral terminal lane\nexport LANE_ID=${shellQuote(manifest.laneId)}\nexport PORT_BASE=${shellQuote(String(manifest.env.PORT_BASE))}\nexport DOBIUS_LANE_LOG_PATH=${shellQuote(manifest.logPath)}\nexport DOBIUS_LANE_RUNTIME_PATH=${shellQuote(manifest.runtimeDataPath)}\n`
}

function shellQuote(value) { return `'${String(value).replaceAll("'", "'\\''")}'` }

export function classifyTerminal({ checkpoint, delta = '', exitCode = null, explicitPermission = false, now = Date.now() }) {
  if (exitCode != null && exitCode !== 0) return { label: 'failed', reason: `exit code ${exitCode}`, hard: true }
  if (explicitPermission || /(?:permission|allow access|approve|waiting for (?:your )?input|press enter)/i.test(delta)) {
    return { label: 'waiting-permission', reason: 'explicit permission or input prompt', hard: true }
  }
  if (checkpoint?.state === 'failed' || checkpoint?.state === 'abandoned') return { label: 'failed', reason: `checkpoint=${checkpoint.state}`, hard: true }
  if (checkpoint?.state === 'waiting_external') return { label: 'needs-human', reason: 'checkpoint waiting_external', hard: true }
  if (checkpoint?.state === 'done' || checkpoint?.state === 'ready_for_review') return { label: 'fine', reason: `checkpoint=${checkpoint.state}`, hard: true }
  const updated = Date.parse(checkpoint?.updatedAt || '')
  if (checkpoint?.state === 'running' && Number.isFinite(updated) && now - updated > 15 * 60 * 1000) {
    return { label: 'stuck', reason: 'running checkpoint is stale', hard: true }
  }
  if (/\b(?:error|failed|fatal|panic|exception|traceback)\b/i.test(delta)) return { label: 'failed', reason: 'failure text', hard: true }
  if (/\b(?:building|compiling|installing|running|working|progress|tests?\b.*\bpass)/i.test(delta)) return { label: 'working', reason: 'work text', hard: false }
  return { label: checkpoint?.state === 'running' ? 'working' : 'fine', reason: 'no escalation signal', hard: false }
}

export function terminalIdentity(terminal) {
  return terminal?.handle || terminal?.id || terminal?.terminalId || null
}

export function checkpointFilename(root, terminal) {
  const id = terminalIdentity(terminal)
  if (!id) return null
  return join(root, `${basename(id).replace(/[^a-zA-Z0-9._-]/g, '_')}.terminal-state.json`)
}
