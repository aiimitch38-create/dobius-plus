import type { SessionWorkspaceFacts } from './session-workspace-facts'
import {
  DOBIUS_COMMANDS,
  DOBIUS_FEATURE_MAP,
  DOBIUS_OFF_LIMITS
} from './session-workspace-feature-map'

export const WORKSPACE_BRIEF_FILENAME = 'CLAUDE.local.md'
// Why: the only proof a CLAUDE.local.md is ours to overwrite. A file without
// this exact first-line prefix is the user's and is never touched.
export const WORKSPACE_BRIEF_MARKER = '<!-- dobius-generated-workspace-brief'

// Future seam: ADAM's resolveContextPack for the observed worktree path.
export type WorkspaceContextPack = { summary: string }

// Branch and repo names are user-controlled; keep them inside their code spans.
function codeSpan(value: string): string {
  return `\`${value.replace(/[`\r\n]/g, "'")}\``
}

function describeDirty(dirty: SessionWorkspaceFacts['dirty']): string {
  if (dirty === 'unknown') {
    return 'unknown (git status failed or timed out)'
  }
  if (dirty.tracked === 0 && dirty.untracked === 0) {
    return 'clean'
  }
  return `dirty: ${dirty.tracked} changed tracked file(s), ${dirty.untracked} untracked`
}

function describeGate(gate: SessionWorkspaceFacts['gate']): string {
  if (gate === 'running') {
    return 'crew running: autonomous agent runs are allowed'
  }
  if (gate === 'paused') {
    return 'crew PAUSED: autonomous agent runs are blocked until resumed on the Agents page'
  }
  return 'crew control file UNREADABLE: autonomous agent runs are blocked (fail closed)'
}

function describeBranch(facts: SessionWorkspaceFacts): string {
  const head = facts.headShort ? ` (HEAD ${codeSpan(facts.headShort)})` : ''
  return facts.branch ? `${codeSpan(facts.branch)}${head}` : `detached HEAD${head}`
}

function dobiusSections(): string[] {
  const rows = DOBIUS_FEATURE_MAP.map(
    (feature) =>
      `| ${feature.component} | ${feature.paths.map((p) => `\`${p}\``).join(', ')} | ${feature.layer} |`
  )
  return [
    '## What this is',
    '',
    'Dobius+ V2, an Electron app (main / preload / renderer) under `dobius/`. The repo root is the legacy V1 app. Agent rules: `dobius/AGENTS.md`.',
    '',
    '## Feature map (component, paths, layer)',
    '',
    '| Component | Paths | Layer |',
    '|---|---|---|',
    ...rows,
    '',
    '## Build and test (run from `dobius/`)',
    '',
    '```bash',
    ...DOBIUS_COMMANDS,
    '```',
    '',
    '## Off-limits',
    '',
    ...DOBIUS_OFF_LIMITS.map((rule) => `- ${rule}`)
  ]
}

function genericSections(facts: SessionWorkspaceFacts): string[] {
  const commands =
    facts.packageManager && facts.packageScripts.length > 0
      ? facts.packageScripts.map((name) => `- \`${facts.packageManager} run ${name}\``)
      : ['- No build/test scripts detected in `package.json`; check the repo README.']
  return [
    '## Build and test',
    '',
    ...commands,
    '',
    '## Off-limits',
    '',
    '- Never commit this file.',
    '- Never read or print secret files (`.env*`, tokens, credentials).'
  ]
}

export function renderSessionWorkspaceBrief(
  facts: SessionWorkspaceFacts,
  generatedAt: Date,
  contextPack: WorkspaceContextPack | null
): string {
  const lines = [
    `${WORKSPACE_BRIEF_MARKER} v1: Dobius+ rewrites this file at each session start. Delete this line to keep your own edits; Dobius+ then leaves the file alone. -->`,
    '# Workspace brief (generated)',
    '',
    `Generated by Dobius+ at ${generatedAt.toISOString()}. Local to this checkout and git-ignored; never commit it.`,
    '',
    '## Where you are',
    '',
    `- Worktree: ${codeSpan(facts.worktreeRoot)} (${facts.isLinkedWorktree ? 'linked git worktree' : 'main checkout'})`,
    `- Repository: ${codeSpan(facts.repoName)}`,
    `- Branch: ${describeBranch(facts)}`,
    `- Working tree at session start: ${describeDirty(facts.dirty)}`,
    `- Execution gate (Pause crew): ${describeGate(facts.gate)}`,
    '',
    ...(facts.isDobiusRepo ? dobiusSections() : genericSections(facts)),
    '',
    '## ADAM context pack',
    '',
    contextPack
      ? contextPack.summary
      : 'Not available for this session; this brief uses live git facts and the checked-in feature map only.',
    ''
  ]
  return lines.join('\n')
}
