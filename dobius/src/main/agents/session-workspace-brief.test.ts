import { execFileSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync
} from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const control = vi.hoisted(() => ({
  state: {
    paused: false,
    status: 'ok' as 'ok' | 'missing' | 'unreadable',
    detail: null as string | null
  }
}))

vi.mock('./agents-config-store', () => ({
  getAgentsControlState: () => ({ ...control.state, filePath: '/data/agents-config.json' })
}))

import {
  refreshSessionWorkspaceBrief,
  scheduleSessionWorkspaceBriefRefresh,
  WORKSPACE_BRIEF_REFRESH_TTL_MS,
  type SessionWorkspaceBriefDeps
} from './session-workspace-brief'
import { WORKSPACE_BRIEF_MARKER } from './session-workspace-brief-render'
import { DOBIUS_REPO_IDENTITY_PATH } from './session-workspace-feature-map'

const FIXED_NOW = new Date('2026-09-25T12:00:00.000Z')
const noAdam: SessionWorkspaceBriefDeps = { contextPack: async () => null, now: () => FIXED_NOW }

let scratch: string

function git(cwd: string, ...args: string[]): string {
  return execFileSync('git', args, { cwd, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] })
}

function makeRepo(name = 'sample-repo'): string {
  const repo = path.join(scratch, name)
  mkdirSync(repo, { recursive: true })
  git(repo, 'init', '-q', '-b', 'main')
  git(repo, 'config', 'user.email', 'test@example.invalid')
  git(repo, 'config', 'user.name', 'Test')
  git(repo, 'config', 'commit.gpgsign', 'false')
  writeFileSync(path.join(repo, 'README.md'), 'hello\n')
  mkdirSync(path.join(repo, 'pkg'))
  writeFileSync(path.join(repo, 'pkg', 'a.ts'), 'export {}\n')
  git(repo, 'add', '.')
  git(repo, 'commit', '-q', '-m', 'init')
  return repo
}

function briefPath(root: string): string {
  return path.join(root, 'CLAUDE.local.md')
}

beforeEach(() => {
  scratch = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'workspace-brief-')))
  control.state = { paused: false, status: 'ok', detail: null }
})

afterEach(() => {
  rmSync(scratch, { recursive: true, force: true })
  vi.restoreAllMocks()
})

describe('refreshSessionWorkspaceBrief', () => {
  it('writes CLAUDE.local.md at the worktree root with live facts, even from a subfolder', async () => {
    const repo = makeRepo()
    writeFileSync(path.join(repo, 'README.md'), 'changed\n')
    writeFileSync(path.join(repo, 'new-file.txt'), 'x\n')

    const result = await refreshSessionWorkspaceBrief(path.join(repo, 'pkg'), noAdam)

    expect(result).toEqual({ status: 'written', filePath: briefPath(repo) })
    const text = readFileSync(briefPath(repo), 'utf-8')
    expect(text.startsWith(WORKSPACE_BRIEF_MARKER)).toBe(true)
    expect(text).toContain(`Worktree: \`${repo}\` (main checkout)`)
    expect(text).toContain('Repository: `sample-repo`')
    expect(text).toMatch(/Branch: `main` \(HEAD `[0-9a-f]{7,}`\)/)
    expect(text).toContain('dirty: 1 changed tracked file(s), 1 untracked')
    expect(text).toContain(
      'Execution gate (Pause crew) as of 2026-09-25T12:00:00.000Z: crew was running'
    )
    expect(text).toContain('Generated by Dobius+ as of 2026-09-25T12:00:00.000Z; may be stale.')
    expect(text.split('\n')[0]).toBe(
      `${WORKSPACE_BRIEF_MARKER} v1: generated by Dobius+ as of 2026-09-25T12:00:00.000Z; may be stale. Delete this line to keep your own edits; Dobius+ then leaves the file alone. -->`
    )
    expect(text).not.toContain('each session start')
    expect(text).toContain(`This brief describes only the checkout at \`${repo}\``)
    expect(existsSync(path.join(repo, 'pkg', 'CLAUDE.local.md'))).toBe(false)
  })

  it('makes git ignore the brief through .git/info/exclude so it can never be committed', async () => {
    const repo = makeRepo()

    await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(git(repo, 'status', '--porcelain')).toBe('')
    expect(readFileSync(path.join(repo, '.git', 'info', 'exclude'), 'utf-8')).toContain(
      '/CLAUDE.local.md'
    )
    expect(git(repo, 'check-ignore', 'CLAUDE.local.md').trim()).toBe('CLAUDE.local.md')
  })

  it('does not touch info/exclude when the repo already ignores the file', async () => {
    const repo = makeRepo()
    writeFileSync(path.join(repo, '.gitignore'), 'CLAUDE.local.md\n')
    const excludePath = path.join(repo, '.git', 'info', 'exclude')
    const before = existsSync(excludePath) ? readFileSync(excludePath, 'utf-8') : null

    await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(existsSync(excludePath) ? readFileSync(excludePath, 'utf-8') : null).toBe(before)
    expect(existsSync(briefPath(repo))).toBe(true)
  })

  it('describes a linked worktree and ignores the brief there too', async () => {
    const repo = makeRepo()
    const linked = path.join(scratch, 'linked-wt')
    git(repo, 'worktree', 'add', '-q', '-b', 'feature/x', linked)

    const result = await refreshSessionWorkspaceBrief(linked, noAdam)

    expect(result.status).toBe('written')
    const text = readFileSync(briefPath(linked), 'utf-8')
    expect(text).toContain(`Worktree: \`${linked}\` (linked git worktree)`)
    expect(text).toContain('Repository: `sample-repo`')
    expect(text).toContain('Branch: `feature/x`')
    expect(text).toContain('Working tree as of 2026-09-25T12:00:00.000Z: clean')
    expect(git(linked, 'status', '--porcelain')).toBe('')
  })

  it('never overwrites a user-authored CLAUDE.local.md', async () => {
    const repo = makeRepo()
    writeFileSync(briefPath(repo), '# my own notes\n')
    const info = vi.spyOn(console, 'info').mockImplementation(() => undefined)

    const result = await refreshSessionWorkspaceBrief(repo, noAdam)
    await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(result).toEqual({
      status: 'skipped',
      reason: 'user-authored',
      filePath: briefPath(repo)
    })
    expect(readFileSync(briefPath(repo), 'utf-8')).toBe('# my own notes\n')
    const skipLogs = info.mock.calls.filter((call) => String(call[0]).includes('left'))
    expect(skipLogs).toHaveLength(1)
  })

  it('treats a symlink at CLAUDE.local.md as user-authored and leaves it alone', async () => {
    const repo = makeRepo()
    const target = path.join(scratch, 'elsewhere.md')
    writeFileSync(target, `${WORKSPACE_BRIEF_MARKER} pretend -->\n`)
    symlinkSync(target, briefPath(repo))

    const result = await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(result.status).toBe('skipped')
    expect(readFileSync(target, 'utf-8')).toBe(`${WORKSPACE_BRIEF_MARKER} pretend -->\n`)
  })

  it('regenerates its own earlier brief with current facts', async () => {
    const repo = makeRepo()
    await refreshSessionWorkspaceBrief(repo, noAdam)
    git(repo, 'checkout', '-q', '-b', 'second-branch')

    const result = await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(result.status).toBe('written')
    expect(readFileSync(briefPath(repo), 'utf-8')).toContain('Branch: `second-branch`')
  })

  it('skips folders that are not git worktrees and never writes into them', async () => {
    const plain = path.join(scratch, 'plain-folder')
    mkdirSync(plain)

    await expect(refreshSessionWorkspaceBrief(plain, noAdam)).resolves.toEqual({
      status: 'skipped',
      reason: 'not-a-git-worktree'
    })
    await expect(
      refreshSessionWorkspaceBrief(path.join(scratch, 'missing'), noAdam)
    ).resolves.toEqual({ status: 'skipped', reason: 'not-a-git-worktree' })
    expect(existsSync(briefPath(plain))).toBe(false)
  })

  it('reports the Pause crew gate state, including fail-closed unreadable', async () => {
    const repo = makeRepo()
    control.state = { paused: true, status: 'ok', detail: null }
    await refreshSessionWorkspaceBrief(repo, noAdam)
    expect(readFileSync(briefPath(repo), 'utf-8')).toContain('crew was PAUSED')

    control.state = { paused: false, status: 'unreadable', detail: 'bad json' }
    await refreshSessionWorkspaceBrief(repo, noAdam)
    const text = readFileSync(briefPath(repo), 'utf-8')
    expect(text).toContain('crew control file was UNREADABLE')
    expect(text).not.toContain('bad json')
  })

  it('never includes env values or script bodies, only script names', async () => {
    const repo = makeRepo()
    writeFileSync(
      path.join(repo, 'package.json'),
      JSON.stringify({
        scripts: {
          build: 'API_TOKEN=sk-live-SECRETVALUE vite build',
          'test:unit': 'vitest',
          deploy: 'push-it'
        }
      })
    )
    writeFileSync(path.join(repo, 'pnpm-lock.yaml'), '')
    vi.stubEnv('WORKSPACE_BRIEF_TEST_SECRET', 'env-SECRETVALUE-123')

    await refreshSessionWorkspaceBrief(repo, noAdam)

    const text = readFileSync(briefPath(repo), 'utf-8')
    expect(text).toContain('`pnpm run build`')
    expect(text).toContain('`pnpm run test:unit`')
    expect(text).not.toContain('deploy')
    expect(text).not.toContain('SECRETVALUE')
    vi.unstubAllEnvs()
  })

  it('adds the Dobius+ feature map, commands and off-limits list in the Dobius+ repo', async () => {
    const repo = makeRepo('dobius-plus')
    mkdirSync(path.dirname(path.join(repo, DOBIUS_REPO_IDENTITY_PATH)), { recursive: true })
    writeFileSync(path.join(repo, DOBIUS_REPO_IDENTITY_PATH), 'export {}\n')

    await refreshSessionWorkspaceBrief(repo, noAdam)

    const text = readFileSync(briefPath(repo), 'utf-8')
    expect(text).toContain('## Feature map (component, paths, layer)')
    expect(text).toContain('| Agent runs, hard rails, Pause crew gate |')
    expect(text).toContain('pnpm run typecheck')
    expect(text).toContain('~/Library/Application Support/dobius-plus/')
  })

  it('logs once when ADAM is unavailable and uses a context pack when one is provided', async () => {
    const repo = makeRepo()
    const info = vi.spyOn(console, 'info').mockImplementation(() => undefined)

    await refreshSessionWorkspaceBrief(repo)
    await refreshSessionWorkspaceBrief(repo)

    const adamLogs = info.mock.calls.filter((call) => String(call[0]).includes('ADAM'))
    expect(adamLogs).toHaveLength(1)
    expect(readFileSync(briefPath(repo), 'utf-8')).toContain(
      '## ADAM context pack\n\nNot available'
    )

    await refreshSessionWorkspaceBrief(repo, {
      contextPack: async () => ({ summary: 'Pack from ADAM for this worktree.' }),
      now: () => FIXED_NOW
    })
    expect(readFileSync(briefPath(repo), 'utf-8')).toContain('Pack from ADAM for this worktree.')
  })

  it('shares one refresh between concurrent callers for the same folder', async () => {
    const repo = makeRepo()

    const [first, second] = await Promise.all([
      refreshSessionWorkspaceBrief(repo, noAdam),
      refreshSessionWorkspaceBrief(repo, noAdam)
    ])

    expect(first).toBe(second)
    const exclude = readFileSync(path.join(repo, '.git', 'info', 'exclude'), 'utf-8')
    expect(exclude.match(/\/CLAUDE\.local\.md/g)).toHaveLength(1)
  })

  it('shares one refresh between callers in different folders of the same worktree', async () => {
    const repo = makeRepo()

    const [fromRoot, fromSubfolder] = await Promise.all([
      refreshSessionWorkspaceBrief(repo, noAdam),
      refreshSessionWorkspaceBrief(path.join(repo, 'pkg'), noAdam)
    ])

    expect(fromRoot).toBe(fromSubfolder)
  })
})

describe('refreshSessionWorkspaceBrief when git will not ignore the file (review F1)', () => {
  function excludeRules(repo: string): number {
    const text = readFileSync(path.join(repo, '.git', 'info', 'exclude'), 'utf-8')
    return text.split('\n').filter((line) => line === '/CLAUDE.local.md').length
  }

  it('adds the exclude rule once and stops retrying a root that re-includes the file', async () => {
    const repo = makeRepo()
    writeFileSync(path.join(repo, '.gitignore'), '!CLAUDE.local.md\n')
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => undefined)

    for (let i = 0; i < 3; i += 1) {
      await expect(refreshSessionWorkspaceBrief(repo, noAdam)).resolves.toMatchObject({
        status: 'skipped',
        reason: 'not-ignorable'
      })
    }

    expect(excludeRules(repo)).toBe(1)
    expect(warn.mock.calls.filter((call) => String(call[0]).includes('ignored'))).toHaveLength(1)
    expect(existsSync(briefPath(repo))).toBe(false)
  })

  it('does not append the rule again when info/exclude already has it', async () => {
    const repo = makeRepo()
    writeFileSync(path.join(repo, '.gitignore'), '!CLAUDE.local.md\n')
    writeFileSync(path.join(repo, '.git', 'info', 'exclude'), '/CLAUDE.local.md\n')
    vi.spyOn(console, 'warn').mockImplementation(() => undefined)

    await refreshSessionWorkspaceBrief(repo, noAdam)

    expect(readFileSync(path.join(repo, '.git', 'info', 'exclude'), 'utf-8')).toBe(
      '/CLAUDE.local.md\n'
    )
  })

  it('never writes over a tracked brief, even one carrying the marker', async () => {
    const repo = makeRepo()
    writeFileSync(briefPath(repo), `${WORKSPACE_BRIEF_MARKER} committed -->\n`)
    git(repo, 'add', 'CLAUDE.local.md')
    git(repo, 'commit', '-q', '-m', 'track it')
    vi.spyOn(console, 'warn').mockImplementation(() => undefined)

    await expect(refreshSessionWorkspaceBrief(repo, noAdam)).resolves.toMatchObject({
      reason: 'not-ignorable'
    })
    expect(readFileSync(briefPath(repo), 'utf-8')).toBe(`${WORKSPACE_BRIEF_MARKER} committed -->\n`)
    expect(excludeRules(repo)).toBe(1)
  })
})

describe('nested worktrees (review F2)', () => {
  it('skips a main checkout with worktrees nested inside it, but writes in the nested one', async () => {
    const repo = makeRepo()
    const nested = path.join(repo, '.claude', 'worktrees', 'lane-a')
    git(repo, 'worktree', 'add', '-q', '-b', 'lane-a', nested)

    await expect(refreshSessionWorkspaceBrief(repo, noAdam)).resolves.toMatchObject({
      status: 'skipped',
      reason: 'nested-worktrees'
    })
    expect(existsSync(briefPath(repo))).toBe(false)

    await expect(refreshSessionWorkspaceBrief(nested, noAdam)).resolves.toMatchObject({
      status: 'written'
    })
    const text = readFileSync(briefPath(nested), 'utf-8')
    expect(text).toContain(`This brief describes only the checkout at \`${nested}\``)
    expect(text).toContain('belongs to a different checkout')
  })

  it('still writes at a main checkout whose worktrees live elsewhere', async () => {
    const repo = makeRepo()
    git(repo, 'worktree', 'add', '-q', '-b', 'sibling', path.join(scratch, 'sibling-wt'))

    await expect(refreshSessionWorkspaceBrief(repo, noAdam)).resolves.toMatchObject({
      status: 'written'
    })
  })
})

describe('scheduleSessionWorkspaceBriefRefresh (review F3)', () => {
  it('skips git work for a root refreshed within the TTL, then refreshes again', async () => {
    const repo = makeRepo()
    let now = FIXED_NOW.getTime()
    const deps: SessionWorkspaceBriefDeps = {
      contextPack: async () => null,
      now: () => new Date(now)
    }

    await expect(scheduleSessionWorkspaceBriefRefresh(repo, deps)).resolves.toMatchObject({
      status: 'written'
    })
    now += WORKSPACE_BRIEF_REFRESH_TTL_MS - 1
    await expect(
      scheduleSessionWorkspaceBriefRefresh(path.join(repo, 'pkg'), deps)
    ).resolves.toEqual({ status: 'skipped', reason: 'recently-refreshed' })
    // Worktree creation always writes, whatever the TTL says.
    await expect(refreshSessionWorkspaceBrief(repo, deps)).resolves.toMatchObject({
      status: 'written'
    })
    now += WORKSPACE_BRIEF_REFRESH_TTL_MS
    await expect(scheduleSessionWorkspaceBriefRefresh(repo, deps)).resolves.toMatchObject({
      status: 'written'
    })
  })

  it('never rejects, even when the folder is unusable', async () => {
    await expect(
      scheduleSessionWorkspaceBriefRefresh(path.join(scratch, 'nope'), noAdam)
    ).resolves.toEqual({ status: 'skipped', reason: 'not-a-git-worktree' })
  })
})
